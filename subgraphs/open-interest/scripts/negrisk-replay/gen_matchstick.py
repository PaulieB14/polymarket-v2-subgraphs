"""Generate a Matchstick replay test from a real-data fixture (tests/fixtures/negrisk-real/*.json).
Every adapter event is fed through the real handlers in on-chain (block, logIndex) order.
Usage: gen_matchstick.py <fixture.json> <tag> <tolerance_usdc>"""
import json,sys
F=json.load(open(sys.argv[1])); tag=sys.argv[2]; tol=int(float(sys.argv[3])*1e6)
conds=F['conds']; idx={c:i for i,c in enumerate(conds)}
rows=[]
for e in F['events']:
  k=e['k']
  if k=='QP': rows.append('Q')
  elif k in('SP','MG','RD'): rows.append('%s%d:%d'%(k[0],idx[e['c']],e['amt']))
  elif k=='CV': rows.append('C%d:%d'%(e['idx'],e['amt']))
  elif k=='OR': rows.append('O%d:%d'%(int(e['q'][-2:],16),e['out']))
CH=int(sys.argv[4]) if len(sys.argv)>4 else 1500
START=int(sys.argv[5]) if len(sys.argv)>5 else 0
END=int(sys.argv[6]) if len(sys.argv)>6 else len(rows)
def model_state(upto):
  # python port of the current rules, state after the first `upto` rows
  oi=[0]*len(conds); mi=[0]*len(conds); bu=[0]*len(conds); out=[0]*len(conds); n=0; g=0; created=[False]*len(conds)
  for row in rows[:upto]:
    k=row[0]
    if k=='Q': n+=1; continue
    a,v=row[1:].split(':'); a=int(a); v=int(v)
    if k in 'SMR':
      d=v if k=='S' else -v
      if d==0 and not created[a]: continue
      created[a]=True; oi[a]+=d; g+=d
    elif k=='C':
      if v==0 or a==0: continue
      no=[i for i in range(n) if a>>i&1]; yes=[i for i in range(n) if not a>>i&1]
      if not no: continue
      for i in yes:
        if out[i]==2: continue
        mi[i]+=v; oi[i]+=v; created[i]=True
      for i in no:
        if out[i]==1: continue
        bu[i]+=v; oi[i]-=v; created[i]=True
      g-=v*(len(no)-1)
    elif k=='O':
      if out[a]: continue
      out[a]=1 if v==1 else 2
      if v==1:
        if bu[a]: oi[a]+=bu[a]
        bu[a]=0
      else:
        if mi[a]: oi[a]-=mi[a]
        mi[a]=0
  return dict(n=n,oi=oi,mi=mi,bu=bu,out=out,g=g,created=created)
seg_rows=rows[START:END]
ck_in=model_state(START) if START>0 else None
ck_out=model_state(END) if END<len(rows) else None
rows_all=rows
rows=seg_rows
chunks=[';'.join(rows[i:i+CH]) for i in range(0,len(rows),CH)]
seg='' if (START==0 and END==len(rows_all)) else ('-part1' if START==0 else '-part2')
out=[]
out.append('// GENERATED by scripts/negrisk-replay/gen_matchstick.py from %s - do not edit' % sys.argv[1].split('/')[-1])
out.append('import { assert, describe, test, clearStore, log } from "matchstick-as/assembly/index"')
out.append('import { BigInt, Bytes } from "@graphprotocol/graph-ts"')
out.append('import { MarketOpenInterest, NegRiskQuestion, GlobalOpenInterest } from "../generated/schema"')
out.append('import { prepareEvent, addQuestion, split, merge, convert, redeem, report, raw, globalRaw, sumRaw, NrEvent, nextBlock } from "./nr-helpers"')
out.append('const MARKET = "%s"' % F['market'])
out.append('const N = %d' % len(conds))
out.append('const FEE = %d' % F['fee'])
out.append('const TOL = BigInt.fromI64(%d)' % tol)
out.append('const CONDS: string[] = [%s]' % ','.join('"%s"'%c for c in conds))
for i,c in enumerate(chunks): out.append('const CHUNK_%d = "%s"' % (i,c))
out.append('let ev: NrEvent = new NrEvent(Bytes.fromHexString(MARKET))')
out.append('''let minSeen = BigInt.zero()
let events = 0
function check(i: i32): void {
  let x = raw(ev, i)
  if (x.lt(minSeen)) minSeen = x
  assert.assertTrue(!x.lt(BigInt.zero()), "event " + events.toString() + " q" + i.toString() + " negative " + x.toString())
}
function play(chunk: string): void {
  let rows = chunk.split(";")
  for (let r = 0; r < rows.length; r++) {
    let row = rows[r]
    let k = row.charAt(0)
    if (k == "Q") {
      addQuestion(ev)
    } else {
      let parts = row.substr(1).split(":")
      let a = I32.parseInt(parts[0])
      let v = BigInt.fromString(parts[1])
      if (k == "S") split(ev, a, v)
      else if (k == "M") merge(ev, a, v)
      else if (k == "R") redeem(ev, a, v)
      else if (k == "C") convert(ev, BigInt.fromI32(a), v)
      else if (k == "O") report(ev, a, parts[1] == "1")
    }
    events++
    // every event: check the touched question; conversions/reports touch all
    if (k == "C" || k == "O" || k == "Q") {
      for (let i = 0; i < ev.conds.length; i++) check(i)
    } else {
      check(I32.parseInt(row.substr(1).split(":")[0]))
    }
    if (r % 50 == 0) nextBlock()
  }
}''')
seed=''
if ck_in:
  seed+='    addQuestion(ev)\n'*ck_in['n']
  for i in range(len(conds)):
    if ck_in['created'][i]:
      seed+='    seedMarket(%d, "%d")\n' % (i, ck_in['oi'][i])
    if ck_in['mi'][i] or ck_in['bu'][i] or ck_in['out'][i]:
      seed+='    seedQuestion(%d, %d, "%d", "%d")\n' % (i, ck_in['out'][i], ck_in['mi'][i], ck_in['bu'][i])
  seed+='    seedGlobal("%d", %d)\n' % (ck_in['g'], sum(ck_in['created']))
  events0=START
else: events0=0
out.append('''function seedMarket(i: i32, amt: string): void {
  let m = new MarketOpenInterest(ev.cid(i))
  m.conditionId = ev.conds[i]
  m.collateralToken = Bytes.fromHexString("0x2791bca1f2de4661ed88a30c99a7a9449aa84174")
  m.negRisk = true
  m.amountRaw = BigInt.fromString(amt)
  m.amount = m.amountRaw.toBigDecimal()
  m.splitCount = BigInt.zero()
  m.mergeCount = BigInt.zero()
  m.redemptionCount = BigInt.zero()
  m.conversionCount = BigInt.zero()
  m.createdAtBlock = BigInt.zero()
  m.createdAtTimestamp = BigInt.zero()
  m.lastUpdatedBlock = BigInt.zero()
  m.lastUpdatedTimestamp = BigInt.zero()
  m.save()
}
function seedQuestion(i: i32, outcome: i32, minted: string, burned: string): void {
  let q = new NegRiskQuestion(ev.cid(i))
  q.marketId = ev.marketId
  q.questionId = ev.qids[i]
  q.outcome = outcome
  q.mintedRaw = BigInt.fromString(minted)
  q.burnedRaw = BigInt.fromString(burned)
  q.save()
}
function seedGlobal(amt: string, count: i32): void {
  let g = new GlobalOpenInterest("global")
  g.amountRaw = BigInt.fromString(amt)
  g.amount = g.amountRaw.toBigDecimal()
  g.marketCount = count
  g.lastUpdatedBlock = BigInt.zero()
  g.lastUpdatedTimestamp = BigInt.zero()
  g.save()
}''')
out.append('''function setup(): void {
  clearStore()
  ev = prepareEvent(Bytes.fromHexString(MARKET), FEE)
  events = %d
%s}''' % (events0, seed))
out.append('describe("real negRisk event %s%s (%d questions, events %d..%d of %d)", () => {' % (tag,seg,len(conds),START,START+len(rows),len(rows_all)))
out.append('''  test("setup%s", () => {
    setup()
  })''' % (" from checkpoint after event %d (state from scripts/negrisk-replay python port)" % START if ck_in else ""))
for i in range(len(chunks)):
  out.append('  test("replay chunk %d/%d, never negative", () => { play(CHUNK_%d) })' % (i+1,len(chunks),i))
if ck_out:
  lines=''.join('    eqs(%d, "%d")\n' % (i, ck_out['oi'][i]) for i in range(len(conds)))
  out.append('''  test("state after event %d matches the python-port checkpoint (cross-check)", () => {
%s    assert.assertTrue(globalRaw().equals(BigInt.fromString("%d")), "global " + globalRaw().toString())
  })
})
function eqs(i: i32, v: string): void {
  assert.assertTrue(raw(ev, i).equals(BigInt.fromString(v)), "q" + i.toString() + " " + raw(ev, i).toString() + " != " + v)
}''' % (END, lines, ck_out['g']))
else:
  out.append('''  test("settled: every question within tolerance of 0, sum == global", () => {
    assert.i32Equals(N, ev.conds.length)
    for (let i = 0; i < N; i++) assert.stringEquals(CONDS[i], ev.cid(i))
    let worst = BigInt.zero()
    for (let i = 0; i < N; i++) {
      let x = raw(ev, i)
      if (x.gt(worst)) worst = x
      assert.assertTrue(!x.gt(TOL), "q" + i.toString() + " left " + x.toString())
    }
    assert.assertTrue(sumRaw(ev).equals(globalRaw()), "sum " + sumRaw(ev).toString() + " != global " + globalRaw().toString())
    log.info("REAL %s: events={} worstQuestion={} sum={} global={} minEver={}", [events.toString(), worst.toString(), sumRaw(ev).toString(), globalRaw().toString(), minSeen.toString()])
  })
})''' % tag)
open('tests/real-%s%s.test.ts'%(tag,seg),'w').write('\n'.join(out)+'\n')
print('wrote tests/real-%s%s.test.ts rows=%d chunks=%d'%(tag,seg,len(rows),len(chunks)))
